export type ListingEditMessageKey = keyof typeof listingEditMessages.en;
/** State stores stable codes. Render using the current profile language. */
export function translateListingEditMessage(language: string | null | undefined, message: string | null | undefined, params?: TranslationParams): string {
  if (!message) return "";
  if (isListingInputMessage(message)) return translateListingInputMessage(language, message, params);
  const key = Object.hasOwn(listingEditMessages.en, message) ? message as ListingEditMessageKey : "unknownError";
  return getCatalogTranslation(language, listingEditMessages, key, params);
}
