export type ListingCreateMessageKey = keyof typeof listingCreateMessages.en;
/** Presentation only: never used for journal keys, request identity or payload language. */
export function translateListingCreateMessage(language: string | null | undefined, message: string | null | undefined, params?: TranslationParams): string {
  if (!message) return "";
  if (isListingInputMessage(message)) return translateListingInputMessage(language, message, params);
  const key = Object.hasOwn(listingCreateMessages.en, message) ? message as ListingCreateMessageKey : "unknownError";
  return getCatalogTranslation(language, listingCreateMessages, key, params);
}
