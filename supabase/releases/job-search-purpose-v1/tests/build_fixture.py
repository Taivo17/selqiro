"""Compile real accepted job readers/writers into an isolated synthetic fixture."""
from pathlib import Path
import importlib.util

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('release_builder', ROOT / 'generator/build.py')
b = importlib.util.module_from_spec(spec)
spec.loader.exec_module(b)
sources = []


def actual(rel, name):
    sql, body = b.function(b.read(rel), name)
    sources.append({'function': name, 'source': rel, 'source_sha256': b.sha(b.read(rel)), 'body_sha256': b.sha(body)})
    return sql + '\n'


# This accepted fixture already compiles real actor/policy/normalization/writer
# functions, synthetic Auth/identity relations and the real account foundation.
# Do not import its generator or suite (which would modify earlier work).
fixture_rel = 'supabase/releases/account-job-write-fence-v1/tests/fixture.sql'
sql = b.read(fixture_rel) + '\n'
sql += b.read('supabase/releases/account-job-write-fence-v1/account-availability.sql') + '\n'
sql += b.read('supabase/releases/account-job-write-fence-v1/mutate.sql') + '\n'
sql += '''
-- Synthetic provider/block relations, matching the semantics the real readers use.
CREATE TABLE public.user_blocks(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 blocker_id uuid NOT NULL,blocked_id uuid NOT NULL,UNIQUE(blocker_id,blocked_id));
CREATE INDEX user_blocks_blocked_blocker_idx_v1 ON public.user_blocks(blocked_id,blocker_id);
ALTER TABLE public.user_blocks ENABLE ROW LEVEL SECURITY;
CREATE SCHEMA provider_controls_private;
CREATE TABLE provider_controls_private.hidden_providers(viewer_user_id uuid NOT NULL,
 provider_identity_id uuid NOT NULL,revision uuid NOT NULL DEFAULT gen_random_uuid(),hidden_until timestamptz,
 PRIMARY KEY(viewer_user_id,provider_identity_id));
CREATE INDEX hidden_providers_active_idx ON provider_controls_private.hidden_providers(viewer_user_id,hidden_until);
ALTER TABLE provider_controls_private.hidden_providers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON SCHEMA provider_controls_private FROM PUBLIC,anon,authenticated,service_role;
REVOKE ALL ON public.user_blocks,provider_controls_private.hidden_providers FROM PUBLIC,anon,authenticated,service_role;
-- Avatar storage is unrelated to the search predicate. Actual public_fields
-- still calls this boundary; the fixture substitutes only its image URL result.
CREATE SCHEMA profile_media_private;
CREATE FUNCTION profile_media_private.slot_url(uuid,text) RETURNS text LANGUAGE sql STABLE AS $$ SELECT NULL::text $$;
REVOKE ALL ON SCHEMA profile_media_private FROM PUBLIC,anon,authenticated,service_role;
REVOKE ALL ON FUNCTION profile_media_private.slot_url(uuid,text) FROM PUBLIC,anon,authenticated,service_role;
'''
for rel, name in [
    ('supabase/repairs/20261121_personal_jobs/03_visibility.sql', 'jobs_private.is_public'),
    ('supabase/repairs/20261121_job_image_read/01_public_fields.sql', 'jobs_private.public_fields'),
    ('supabase/releases/account-job-read-fence-v1/visible-to-viewer.sql', 'jobs_private.visible_to_viewer'),
    ('supabase/repairs/20261121_personal_jobs/04_reads.sql', 'public.search_public_jobs_v1'),
]:
    sql += actual(rel, name)

# Copy known ACL facts, including app-denied writer helpers and public reader ACL.
for f in b.base['dependencies'] + b.before['functions']:
    if f['signature'] == 'listing_publication_private.hosted_storage_contract_ready()':
        continue
    sql += 'REVOKE ALL ON FUNCTION ' + f['signature'] + ' FROM PUBLIC,anon,authenticated,service_role;\n'
    for grant in f['acl']:
        if grant['grantee'] != 'postgres':
            sql += 'GRANT ' + grant['privilege'] + ' ON FUNCTION ' + f['signature'] + ' TO ' + grant['grantee'] + (' WITH GRANT OPTION' if grant['grantable'] else '') + ';\n'
b.write(ROOT / 'tests/fixture.sql', sql)
b.jwrite(ROOT / 'proof/fixture-provenance.json', {
    'format': 'selqiro-job-search-purpose-fixture-v1',
    'postgres_required': '17.6',
    'accepted_fixture': {'path': fixture_rel, 'sha256': b.sha(b.read(fixture_rel))},
    'accepted_writer_overlay': {
        rel: b.sha(b.read(rel)) for rel in [
            'supabase/releases/account-job-write-fence-v1/account-availability.sql',
            'supabase/releases/account-job-write-fence-v1/mutate.sql'
        ]
    },
    'reader_sources': sources,
    'inherited_substitutions': b.jread('supabase/releases/account-job-write-fence-v1/proof/fixture-provenance.json')['substitutions'],
    'additional_substitutions': [
        {'object': 'profile_media_private.slot_url(uuid,text)', 'reason': 'Unrelated avatar-media boundary returns NULL; real public_fields and all search/visibility/account functions execute.'},
        {'object': 'provider controls / block relations', 'reason': 'Minimal synthetic relations and rows for real hidden-provider/bilateral-block predicates. Production metadata remains independently exact-pinned.'}
    ],
    'target_metadata_exact': True,
    'test_only_base_adaptation': 'Only BASE metadata is adapted to synthetic fixture facts for transaction tests. Production target BEFORE/AFTER metadata is unchanged. Unmodified production preflight must reject fixture BASE.',
    'production_data_used': False
})
print('fixture_bytes', len(sql.encode()))
